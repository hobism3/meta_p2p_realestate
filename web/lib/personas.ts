export type NegotiationPolicy =
  | { kind: "none" }
  | { kind: "undecided" }
  | { kind: "ranged"; min: number; max: number };

export interface ListingPersona {
  personaId: string;
  listingId: string;
  name: string;
  role: "seller" | "landlord";
  personality: string;
  tone: string;
  style: string;
  negotiation: string;
  policy: NegotiationPolicy;
  unknownResponse: string;
}

const SELLER = "AI 매도자";
const LANDLORD = "AI 임대인";

function p(
  listingId: string,
  role: "seller" | "landlord",
  personality: string,
  tone: string,
  style: string,
  negotiation: string,
  policy: NegotiationPolicy,
  unknownResponse: string,
): ListingPersona {
  const n = listingId.replace(/^s0?/, "");
  return {
    personaId: `p-${n}`,
    listingId,
    name: role === "seller" ? SELLER : LANDLORD,
    role,
    personality,
    tone,
    style,
    negotiation,
    policy,
    unknownResponse,
  };
}

